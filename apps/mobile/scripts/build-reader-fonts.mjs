#!/usr/bin/env node
// Compressed offline font families; documents include only the selected family.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const faces = [
  ['TextStack', '../../../web/src/assets/fonts/TextStack-Regular.woff2', 400, 'normal'],
  ['TextStack', '../../../web/src/assets/fonts/TextStack-Italic.woff2', 400, 'italic'],
  ['TextStack', '../../../web/src/assets/fonts/TextStack-Bold.woff2', 700, 'normal'],
  ['TextStack', '../../../web/src/assets/fonts/TextStack-BoldItalic.woff2', 700, 'italic'],
  ['Source Sans 3', 'SourceSans3-Regular.woff2', 400, 'normal'],
  ['Source Sans 3', 'SourceSans3-It.woff2', 400, 'italic'],
  ['Source Sans 3', 'SourceSans3-Bold.woff2', 700, 'normal'],
  ['Source Sans 3', 'SourceSans3-BoldIt.woff2', 700, 'italic'],
]
const families = {}
for (const [family, file, weight, style] of faces) {
  const bytes = readFileSync(new URL(`../assets/fonts/${file}`, import.meta.url))
  if (bytes.subarray(0, 4).toString('ascii') !== 'wOF2') throw new Error(`${file} is not WOFF2`)
  families[family] ??= ''
  families[family] += `@font-face { font-family: '${family}'; src: url(data:font/woff2;base64,${bytes.toString('base64')}) format('woff2'); font-weight: ${weight}; font-style: ${style}; font-display: swap; }\n`
}
const out = new URL('../src/lib/readerFonts.generated.ts', import.meta.url)
writeFileSync(out, `// Generated by pnpm -C apps/mobile build:reader-fonts. Do not edit.\nexport const readerFontFamilies: Record<string, string> = ${JSON.stringify(families)}\n`)
console.log(`Generated ${fileURLToPath(out)}`)
