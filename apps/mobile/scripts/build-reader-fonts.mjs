#!/usr/bin/env node
// Inline bundled fonts for the offline WebView, using the same assets as native screens.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const faces = [
  ['TextStack', 'TextStack-Regular.ttf', 400, 'normal'],
  ['TextStack', 'TextStack-Italic.ttf', 400, 'italic'],
  ['TextStack', 'TextStack-Bold.ttf', 700, 'normal'],
  ['TextStack', 'TextStack-BoldItalic.ttf', 700, 'italic'],
  ['Source Sans 3', 'SourceSans3-Regular.ttf', 400, 'normal'],
]
const css = faces.map(([family, file, weight, style]) => {
  const bytes = readFileSync(new URL(`../assets/fonts/${file}`, import.meta.url))
  if (bytes.readUInt32BE(0) !== 0x00010000) throw new Error(`${file} is not a TrueType font`)
  return `@font-face { font-family: '${family}'; src: url(data:font/ttf;base64,${bytes.toString('base64')}) format('truetype'); font-weight: ${weight}; font-style: ${style}; font-display: swap; }`
}).join('\n')
const out = new URL('../src/lib/readerFonts.generated.ts', import.meta.url)
writeFileSync(out, `// Generated by pnpm -C apps/mobile build:reader-fonts. Do not edit.\nexport const readerFontFaceCss = ${JSON.stringify(css)}\n`)
console.log(`Generated ${fileURLToPath(out)}`)
